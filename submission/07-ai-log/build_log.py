"""Check ai-augmentation-log.jsonl and write summary.md from it and the auto/ logs.

Checks: every record has the required fields, ids are unique, related_ids point
at real records, and every artifact path exists in the repo.

Usage (from the repo root):
  python submission/07-ai-log/build_log.py
"""
import collections
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
REQUIRED = [
    "id", "timestamp", "stage", "agent", "agent_name", "agent_type", "ai_tool", "model", "mode",
    "related_ids", "parent_task", "context", "request", "prompt", "skills_used", "subagents_used",
    "mcp_tools_used", "tools_used", "actions_outputs", "human_decision", "human_intervention",
    "action_verification", "limitation", "status", "outcome", "artifacts", "evidence",
]
OUTCOMES = {"successful", "partially completed", "required rework"}


def read_jsonl(path):
    with open(path, encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def check(records):
    problems, ids = [], set()
    for rec in records:
        rid = rec.get("id", "?")
        problems += [f"{rid}: missing {field}" for field in REQUIRED if field not in rec]
        if rid in ids:
            problems.append(f"{rid}: duplicate id")
        ids.add(rid)
        if rec.get("outcome") not in OUTCOMES:
            problems.append(f"{rid}: outcome must be one of {sorted(OUTCOMES)}")
        problems += [f"{rid}: artifact not found: {a}" for a in rec.get("artifacts", [])
                     if not (REPO / a).exists() and not a.endswith("summary.md")]
    for rec in records:
        problems += [f'{rec["id"]}: unknown related id {r}' for r in rec.get("related_ids", []) if r not in ids]
    return problems


def cell(text):
    return str(text or "").replace("|", "/").replace("\n", " ")


def main():
    records = read_jsonl(HERE / "ai-augmentation-log.jsonl")
    problems = check(records)
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    turns = read_jsonl(HERE / "auto" / "session-turns.jsonl")
    subagents = read_jsonl(HERE / "auto" / "subagents.jsonl")
    calls = read_jsonl(HERE / "auto" / "tool-calls.jsonl")

    lines = ["# AI augmentation log: summary", "",
             "Generated by `build_log.py` from `ai-augmentation-log.jsonl` and the `auto/` logs. Do not edit by hand.", "",
             "## Interactions", "",
             "| Time (UTC) | Stage | Agent / model | Request | Human intervention | Outcome |",
             "|---|---|---|---|---|---|"]
    for rec in sorted(records, key=lambda r: r["timestamp"]):
        lines.append(f'| {rec["timestamp"][:16].replace("T", " ")} | {rec["stage"]} | '
                     f'{cell(rec["agent_name"])} ({rec["agent_type"]}, {rec["model"]}, {rec["mode"]}) | '
                     f'{cell(rec["request"])} | {cell(rec["human_intervention"])} | {rec["outcome"]} |')

    outcomes = collections.Counter(r["outcome"] for r in records)
    by_model = collections.Counter(m for s in subagents for m in s["model"])
    tools = collections.Counter(c["tool"] for c in calls)
    permissions = collections.Counter((c["permission"] or "none").split(":")[0] for c in calls)
    lines += ["", "## Totals from the automatic logs", "",
              f'- Human prompts (turns): {len(turns)}',
              f'- Tool calls: {len(calls)} (main agent {sum(c["session"] == "main" for c in calls)}, '
              f'sub-agents {sum(c["session"] != "main" for c in calls)})',
              f'- Sub-agents: {len(subagents)} ({", ".join(f"{n} x {m}" for m, n in by_model.items())})',
              f'- Tool calls that returned an error: {sum(c["error"] for c in calls)}',
              f'- Permission decisions: {dict(permissions)}',
              f'- Outcomes of curated records: {dict(outcomes)}',
              "", "Most used tools:", ""]
    lines += [f"- `{name}`: {count}" for name, count in tools.most_common(10)]
    lines += ["", "## Turns", "", "| Turn | Start (UTC) | Prompt (first 90 chars) | Files written | Sub-agents |", "|---|---|---|---|---|"]
    for turn in turns:
        lines.append(f'| {turn["id"]} | {turn["start"][:16].replace("T", " ")} | {cell(turn["prompt"][:90])} | '
                     f'{len(turn["files_written"])} | {len(turn["subagents_started"])} |')

    (HERE / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(records)} records OK, summary.md written")


if __name__ == "__main__":
    main()
